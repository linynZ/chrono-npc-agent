"""Synthesize the SFT dataset that targets the local model's measured gaps.

The cloud model passes the guardrail eval at 100% and uses tools; the local
model holds persona but does not call tools and invents facts it lacks
(Finding 04, README Results). So the dataset teaches exactly four behaviors,
in proportion:

  tool_trace   the biggest gap: user asks history -> assistant CALLS
               lookup_lore -> tool returns real records (live vector index,
               not invented) -> assistant answers grounded in them
  guardrail    pasted quiz questions, jailbreaks, item begging, fight-for-me:
               refuse in character, never name the option
  unknown      questions the record cannot answer: say so in character
               instead of inventing (the anti-hallucination bucket)
  persona      openers, backstory, small talk — keeps the voice from drifting
               while the other buckets pull

Every teacher completion is generated by the cloud model under the REAL
production system prompt (plus, for tool_trace only, a generation-time nudge
to consult the record first — the nudge is NOT saved; samples ship with the
production prompt). Tool results in traces come from the real retriever, so
the model is never trained on invented ground truth. Every sample passes the
production output guardrail, and refusals are additionally screened against
the quiz answer they must not name.

Train/eval hygiene: eval/cases.yaml sentences never appear here. The refusal
bucket covers the same *categories* by design — that is what is being taught —
but the held-out eval sentences stay held out.

Usage:
    python scripts/build_sft_dataset.py            # ~330 samples, a few cents
    python scripts/build_sft_dataset.py --limit 20 # smoke run
"""

