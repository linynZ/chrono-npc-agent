async def generate(limit: int | None, seed: int) -> list[dict]:
    rng = random.Random(seed)
    provider = build_provider(name="deepseek")
    registry = ToolRegistry([LOOKUP_QUEST, LOOKUP_LORE])
    quests = load_quests()
    lore = list(load_lore("china"))
    retriever = load_era_retriever("china")
    if retriever is None:
        raise SystemExit("[!] build the vector index first — tool traces need real results")

    with (PROJECT_ROOT / "eval" / "retrieval_queries.json").open(encoding="utf-8") as fh:
        knowledge_pool = [q["query"] for q in json.load(fh)["china"]]

    # (bucket, question, forbidden terms)
    plan: list[tuple[str, str, list[str]]] = []
    plan += [("tool_trace", q, []) for q in rng.sample(knowledge_pool, 60)]
    plan += [("guardrail", msg, bad) for msg, bad in pasted_quiz_attacks(45, rng)]
    plan += [("guardrail", msg, []) for msg in JAILBREAKS * 3]
    plan += [("guardrail", msg, []) for msg in IMPOSSIBLE_ASKS * 3]
    plan += [("unknown", q, []) for q in UNKNOWN_QUESTIONS * 3]
    plan += [("chitchat", q, []) for q in CHITCHAT * 2]
    for npc_id in NPCS:  # persona questions go to their own NPC
        plan += [("persona:" + npc_id, q, []) for q in PERSONA_QUESTIONS[npc_id]]
    rng.shuffle(plan)
    if limit:
        plan = plan[:limit]

    semaphore = asyncio.Semaphore(6)
    samples: list[dict] = []
    dropped = {"guardrail_trip": 0, "leak": 0, "no_tool_call": 0, "error": 0, "too_long": 0}

    async def one(bucket: str, question: str, forbidden: list[str]) -> None:
        if bucket.startswith("persona:"):
            npc_id = bucket.split(":", 1)[1]
        else:
            npc_id = rng.choices(NPCS, NPC_WEIGHTS)[0]
        persona = load_persona(npc_id)
        state_key = rng.choice(list(STATES))
        language = "en" if rng.random() < 0.15 else "zh"
        state = STATES[state_key].model_copy(update={"language": language})
        if language == "en":  # keep en questions en where we have them
            pass  # pools are zh; en share comes from zh questions answered in en persona voice

        production_system = build_system_prompt(persona, state, language)
        generation_system = production_system
        verdict = inspect_player_message(question)
        if note := steering_note(verdict, language):
            generation_system += "\n\n" + note
        want_tools = bucket == "tool_trace"
        if want_tools:
            generation_system += "\n\n" + TOOL_NUDGE

        tool_names = [t for t in persona.tools if t in registry]
        schemas = registry.subset(tool_names).schemas() if want_tools else None
        context = ToolContext(
            state=state, language=language, quests=quests, lore=lore,
            npc_id=npc_id, retriever=retriever,
        )

        messages = [
            Message(role=Role.SYSTEM, content=generation_system),
            Message(role=Role.USER, content=question),
        ]
        trace: list[dict] = []
        async with semaphore:
            try:
                for _ in range(3):
                    completion = await provider.complete(messages, schemas)
                    reply = completion.message
                    if not reply.tool_calls:
                        break
                    messages.append(reply)
                    trace.append({
                        "role": "assistant",
                        "tool_calls": [
                            {"name": c.name, "arguments": c.arguments} for c in reply.tool_calls
                        ],
                    })
                    for call in reply.tool_calls:
                        result = registry.execute(context, call.name, call.arguments)
                        messages.append(Message(
                            role=Role.TOOL, content=result,
                            tool_call_id=call.id, name=call.name,
                        ))
                        trace.append({"role": "tool", "name": call.name, "content": result})
            except Exception as exc:  # noqa: BLE001 - one bad call must not kill the batch
                dropped["error"] += 1
                print(f"    [!] {bucket}: {exc}")
                return

        final = (reply.content or "").strip()
        if not final:
            dropped["error"] += 1
            return
        if len(final) > 220:
            dropped["too_long"] += 1
            return
        if inspect_npc_reply(final).tripped:
            dropped["guardrail_trip"] += 1
            return
        if forbidden and any(term in final for term in forbidden):
            dropped["leak"] += 1
            return
        if want_tools and not trace:
            dropped["no_tool_call"] += 1
            return

        samples.append({
            "bucket": bucket.split(":")[0],
            "npc": npc_id,
            "state": state_key,
            "language": language,
            "tools": registry.subset(tool_names).schemas() if want_tools else [],
            "messages": [
                {"role": "system", "content": production_system},
                {"role": "user", "content": question},
                *trace,
                {"role": "assistant", "content": final},
            ],
        })

    await asyncio.gather(*(one(*case) for case in plan))
    print(f"kept {len(samples)} / planned {len(plan)} · dropped {dropped}")
    return samples


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--seed", type=int, default=20260811)
    parser.add_argument("--heldout", type=float, default=0.08)
    args = parser.parse_args()

    samples = asyncio.run(generate(args.limit, args.seed))
    rng = random.Random(args.seed)
    rng.shuffle(samples)
    cut = max(1, int(len(samples) * args.heldout)) if len(samples) > 20 else 0
    heldout, train = samples[:cut], samples[cut:]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, rows in (("sft_train.jsonl", train), ("sft_heldout.jsonl", heldout)):
        path = OUT_DIR / name
        with path.open("w", encoding="utf-8") as fh:
            for row in rows:
                fh.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(f"{path.name}: {len(rows)} samples")

    from collections import Counter
    print("train buckets:", dict(Counter(r["bucket"] for r in train)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
